"""Hinweise auf KI-generierte Musik – vorsichtig und nachvollziehbar.

Grundsätze (auch rechtlich wichtig):
* Es gibt KEINEN zuverlässigen Beweis, ob ein Song KI-generiert ist. Die App zeigt deshalb nur
  „Hinweise“ mit Quelle an – nie die Behauptung „ist KI“. Ein falsches Etikett könnte echten
  Künstlern schaden (Persönlichkeits-/Unternehmensrecht), daher: Quelle nennen, Einspruch möglich.
* Quellen (alles, was ohnehin vorliegt – keine zusätzlichen Anfragen):
  1. Community-Tags bei Last.fm (z. B. „ai generated“, „suno“, „udio“)
  2. Angaben in Label/Titel/Künstler (z. B. „Suno“, „Udio“, „AI-generated“)
  3. Deine eigene Markierung (hat immer Vorrang)
* Deezers interne KI-Kennzeichnung ist nicht über die öffentliche API verfügbar und wird bewusst
  nicht über inoffizielle Wege abgefragt.
"""

from __future__ import annotations

import re

from . import store

_NS = "ai_mark"
_TAG_STRONG = re.compile(r"^(ai[- ]?generated|ai[- ]?music|ai[- ]?song|ai[- ]?artist|suno( ai)?|udio|"
                         r"artificial intelligence|generated by ai|ki[- ]?(musik|generiert)|ai slop)$", re.I)
_TAG_WEAK = re.compile(r"^(ai|a\.i\.|ki|clanker)$", re.I)
_META = re.compile(r"\b(suno(\.com| ai)?|udio|boomy|mubert|soundraw|aiva|ai[- ]generated|generated with ai)\b", re.I)


def _key(track) -> str:
    return store.track_key(track)


def mark(track, value: str | None) -> None:
    """value: 'ki' | 'mensch' | None (Markierung entfernen)."""
    store.cache_set(_NS, _key(track), {"mark": value} if value else {})


def user_mark(track) -> str | None:
    d = store.cache_get(_NS, _key(track)) or {}
    return d.get("mark")


def check(track, extra: dict | None = None) -> dict:
    """-> {status, quellen, text}. status: kein_hinweis | hinweis | wahrscheinlich | markiert_ki | markiert_mensch"""
    extra = extra or {}
    um = user_mark(track)
    if um == "ki":
        return {"status": "markiert_ki", "quellen": ["deine Markierung"], "text": "Von dir als KI-generiert markiert"}
    if um == "mensch":
        return {"status": "markiert_mensch", "quellen": ["deine Markierung"], "text": "Von dir als nicht KI markiert"}
    sources, strong = [], 0
    tags = track.tags or {}
    total = sum(tags.values()) or 1
    for tag, w in tags.items():
        t = tag.strip()
        if _TAG_STRONG.match(t):
            strong += 2 if w / total >= 0.05 or w >= 20 else 1
            sources.append(f"Last.fm-Tag „{t}“")
        elif _TAG_WEAK.match(t) and w >= 10 and not _TAG_WEAK.match(track.artist.strip()):
            # (Künstler heißt selbst „AI“, z. B. die japanische Sängerin – dann ist der Tag ihr Name)
            strong += 1
            sources.append(f"Last.fm-Tag „{t}“")
    for field, val in (("Label", extra.get("label")), ("Titel", track.title), ("Künstler", track.artist),
                       ("Album", track.album)):
        if val and _META.search(str(val)):
            strong += 2
            sources.append(f"{field} enthält „{_META.search(str(val))[0]}“")
    if strong >= 3:
        return {"status": "wahrscheinlich", "quellen": sources,
                "text": "Mehrere Hinweise auf KI-generierte Musik – nicht bestätigt"}
    if strong:
        return {"status": "hinweis", "quellen": sources, "text": "Möglicherweise KI-generiert – nicht bestätigt"}
    return {"status": "kein_hinweis", "quellen": [], "text": "Keine Hinweise auf KI (das ist kein Beweis)"}
